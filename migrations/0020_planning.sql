ALTER TABLE task FORCE ROW LEVEL SECURITY;
ALTER TABLE dump_line ENABLE ROW LEVEL SECURITY;
ALTER TABLE dump_line FORCE ROW LEVEL SECURITY;
ALTER TABLE day_entry ENABLE ROW LEVEL SECURITY;
ALTER TABLE day_entry FORCE ROW LEVEL SECURITY;

-- task: every member of the space reads and edits; deleting is for the creator or the space owner.
CREATE POLICY task_read ON task FOR SELECT TO ebb_app USING (app.is_member(space_id));
CREATE POLICY task_insert ON task FOR INSERT TO ebb_app
  WITH CHECK (app.is_member(space_id) AND created_by = app.uid());
CREATE POLICY task_update ON task FOR UPDATE TO ebb_app
  USING (app.is_member(space_id)) WITH CHECK (app.is_member(space_id));
CREATE POLICY task_delete ON task FOR DELETE TO ebb_app
  USING (app.is_member(space_id) AND (created_by = app.uid() OR app.is_owner(space_id)));

CREATE POLICY dump_own ON dump_line FOR ALL TO ebb_app
  USING (user_id = app.uid()) WITH CHECK (user_id = app.uid());
REVOKE DELETE ON dump_line FROM ebb_app;

CREATE POLICY day_own ON day_entry FOR ALL TO ebb_app
  USING (user_id = app.uid()) WITH CHECK (user_id = app.uid());
REVOKE DELETE ON day_entry FROM ebb_app;
