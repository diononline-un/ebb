-- E2-P1: tasks, brain-dump lines and the per-day entry. project_id, parent_id and recurrence_id
-- follow in E5 (0050). Rules: docs/specs/E02-kern.md, names: docs/architektur.md (Glossar).

CREATE TABLE task (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  space_id uuid NOT NULL REFERENCES space (id) ON DELETE CASCADE,
  created_by text NOT NULL DEFAULT app.uid() REFERENCES "user" (id) ON DELETE CASCADE,
  assignee_id text REFERENCES "user" (id) ON DELETE SET NULL,
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
  notes text NOT NULL DEFAULT '' CHECK (char_length(notes) <= 5000),
  next_step text NOT NULL DEFAULT '' CHECK (char_length(next_step) <= 280),
  status text NOT NULL DEFAULT 'todo' CHECK (status IN ('todo', 'doing', 'waiting', 'done', 'skipped')),
  do_date date,
  deadline date,
  must boolean NOT NULL DEFAULT false,
  slot text NOT NULL DEFAULT 'inbox' CHECK (slot IN ('inbox', 'block1', 'block2', 'block3', 'block4', 'errands')),
  position int NOT NULL DEFAULT 0 CHECK (position >= 0),
  anchor boolean NOT NULL DEFAULT false,
  push_count int NOT NULL DEFAULT 0 CHECK (push_count >= 0),
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- The anchor is today's one thing, so it always has a day.
  CONSTRAINT task_anchor_has_day CHECK (NOT anchor OR do_date IS NOT NULL),
  -- Errands are batched, not scheduled: undated, so they never roll over or count as pushed.
  CONSTRAINT task_errands_undated CHECK (slot <> 'errands' OR do_date IS NULL)
);
CREATE INDEX task_day ON task (assignee_id, do_date, slot, position);
CREATE INDEX task_space ON task (space_id);
CREATE UNIQUE INDEX task_one_anchor_per_day ON task (assignee_id, do_date) WHERE anchor;

CREATE TABLE dump_line (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id text NOT NULL DEFAULT app.uid() REFERENCES "user" (id) ON DELETE CASCADE,
  -- Generated by the client before sending, so an offline line replayed twice is stored once.
  client_id uuid NOT NULL,
  text text NOT NULL CHECK (char_length(text) BETWEEN 1 AND 500),
  task_id uuid REFERENCES task (id) ON DELETE SET NULL,
  archived_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, client_id)
);
CREATE INDEX dump_line_active ON dump_line (user_id, created_at) WHERE archived_at IS NULL;

CREATE TABLE day_entry (
  user_id text NOT NULL DEFAULT app.uid() REFERENCES "user" (id) ON DELETE CASCADE,
  date date NOT NULL,
  energy text CHECK (energy IN ('low', 'good')),
  rolled_count int NOT NULL DEFAULT 0 CHECK (rolled_count >= 0),
  ritual_done_at timestamptz,
  PRIMARY KEY (user_id, date)
);

-- One trigger keeps the task invariants the API must not be able to break:
-- personal tasks always belong to the space owner, shared tasks only to members,
-- created_by/created_at never change, updated_at is always fresh.
CREATE FUNCTION app.task_before_write() RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = pg_catalog, public
  AS $$
DECLARE
  v_kind text;
  v_owner text;
BEGIN
  SELECT kind, owner_id INTO v_kind, v_owner FROM space WHERE id = NEW.space_id;
  IF v_kind = 'personal' THEN
    NEW.assignee_id := v_owner;
  ELSIF v_kind = 'shared' AND NEW.assignee_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM space_member WHERE space_id = NEW.space_id AND user_id = NEW.assignee_id
  ) THEN
    RAISE EXCEPTION 'assignee_not_member' USING ERRCODE = 'check_violation';
  END IF;
  -- An unknown space (v_kind NULL) is left to RLS: the WITH CHECK policy rejects the row.
  IF TG_OP = 'UPDATE' THEN
    NEW.created_by := OLD.created_by;
    NEW.created_at := OLD.created_at;
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END
$$;

CREATE TRIGGER task_before_write BEFORE INSERT OR UPDATE ON task
  FOR EACH ROW EXECUTE FUNCTION app.task_before_write();

